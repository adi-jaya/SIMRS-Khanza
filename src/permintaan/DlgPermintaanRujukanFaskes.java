    /**
     * Memuat data permintaan rujukan dari database sesuai filter tanggal, status, dan keyword.
     */
    public void tampil() {
        Valid.tabelKosong(tabMode);
        emptTeks();
        try {
            String sql = "select no_rujukan, tanggal_rujukan, jam_rujukan, nama_fktp, nama_perujuk, no_telp_perujuk, "
                    + "nama_pasien, no_ktp, jk, tgl_lahir, umur, no_telp_pasien, diagnosa, keluhan_utama, "
                    + "tanda_vital_kesadaran, tanda_vital_td, tanda_vital_nadi, tanda_vital_rr, tanda_vital_suhu, tanda_vital_spo2, "
                    + "tindakan_diberikan, transportasi, kebutuhan_khusus, estimasi_tiba, status, catatan_igd "
                    + "from permintaan_rujukan_faskes where tanggal_rujukan between ? and ? ";

            if (!cmbStatus.getSelectedItem().toString().equals("Semua")) {
                sql += "and status = ? ";
            }

            if (!TCari.getText().trim().equals("")) {
                sql += "and (no_rujukan like ? or nama_pasien like ? or no_ktp like ? or nama_fktp like ? or diagnosa like ?) ";
            }

            sql += "order by tanggal_rujukan desc, jam_rujukan desc";

            ps = koneksi.prepareStatement(sql);
            int idx = 1;
            ps.setString(idx++, Valid.SetTgl(DTPCari1.getSelectedItem() + ""));
            ps.setString(idx++, Valid.SetTgl(DTPCari2.getSelectedItem() + ""));

            if (!cmbStatus.getSelectedItem().toString().equals("Semua")) {
                ps.setString(idx++, cmbStatus.getSelectedItem().toString());
            }

            if (!TCari.getText().trim().equals("")) {
                String kw = "%" + TCari.getText().trim() + "%";
                ps.setString(idx++, kw);
                ps.setString(idx++, kw);
                ps.setString(idx++, kw);
                ps.setString(idx++, kw);
                ps.setString(idx++, kw);
            }

            rs = ps.executeQuery();
            while (rs.next()) {
                String tglJam = rs.getString("tanggal_rujukan") + " " + rs.getString("jam_rujukan");
                String tv = "GCS: " + rs.getString("tanda_vital_kesadaran")
                        + " | TD: " + (rs.getString("tanda_vital_td") != null ? rs.getString("tanda_vital_td") : "-")
                        + " | HR: " + (rs.getString("tanda_vital_nadi") != null ? rs.getString("tanda_vital_nadi") + "x/m" : "-")
                        + " | RR: " + (rs.getString("tanda_vital_rr") != null ? rs.getString("tanda_vital_rr") + "x/m" : "-")
                        + " | S: " + (rs.getString("tanda_vital_suhu") != null ? rs.getString("tanda_vital_suhu") + "C" : "-")
                        + " | SpO2: " + (rs.getString("tanda_vital_spo2") != null ? rs.getString("tanda_vital_spo2") + "%" : "-");

                tabMode.addRow(new Object[]{
                    rs.getString("no_rujukan"),
                    tglJam,
                    rs.getString("nama_fktp"),
                    rs.getString("nama_perujuk"),
                    rs.getString("no_telp_perujuk"),
                    rs.getString("nama_pasien"),
                    rs.getString("no_ktp"),
                    rs.getString("jk"),
                    rs.getString("umur"),
                    rs.getString("diagnosa"),
                    tv,
                    rs.getString("transportasi"),
                    rs.getString("estimasi_tiba"),
                    rs.getString("status"),
                    rs.getString("catatan_igd"),
                    rs.getString("keluhan_utama"),
                    rs.getString("tindakan_diberikan"),
                    rs.getString("kebutuhan_khusus"),
                    rs.getString("no_telp_pasien"),
                    rs.getString("tgl_lahir")
                });
            }
        } catch (Exception e) {
            System.out.println("Notifikasi tampil rujukan: " + e);
        } finally {
            try {
                if (rs != null) {
                    rs.close();
                }
                if (ps != null) {
                    ps.close();
                }
            } catch (Exception e) {
            }
        }
        LCount.setText("" + tabMode.getRowCount());
    }

