    private void BtnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnPrintActionPerformed
        if (tabMode.getRowCount() == 0) {
            JOptionPane.showMessageDialog(rootPane, "Maaf, data sudah habis. Tidak ada data yang bisa Anda print..!!");
            return;
        }

        int selectedRow = tbRujukan.getSelectedRow();
        if (selectedRow != -1) {
            Object[] options = {"Resume Rujukan Terpilih", "Daftar Semua Rujukan", "Batal"};
            int choice = JOptionPane.showOptionDialog(rootPane,
                    "Pilih jenis cetakan data rujukan:",
                    "Cetak Dokumen Rujukan",
                    JOptionPane.DEFAULT_OPTION,
                    JOptionPane.QUESTION_MESSAGE,
                    null,
                    options,
                    options[0]);
            if (choice == 0) {
                cetakResume(selectedRow);
            } else if (choice == 1) {
                cetakDaftar();
            }
        } else {
            cetakDaftar();
        }
    }//GEN-LAST:event_BtnPrintActionPerformed

